import { createRequire } from 'node:module'
const require = createRequire('D:/即设-毕设素材/jixian-gallery/')
const { chromium } = require('playwright-core')
const b = await chromium.launch({ executablePath: 'C:/Users/ZhuanZ1/AppData/Local/ms-playwright/chromium-1243/chrome-win64/chrome.exe', headless: true })
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
const p = await ctx.newPage()
const bad = []
p.on('response', (r) => r.status() >= 400 && bad.push(r.status() + ' ' + r.url().slice(0, 60)))
p.on('pageerror', (e) => bad.push('JS: ' + e.message))
await p.goto('https://daolingz46-tech.github.io/jixian-app/', { waitUntil: 'networkidle', timeout: 60000 })
await p.waitForTimeout(2700)
await p.screenshot({ path: 'shots/live-final-login.png' })
await p.fill('#phone', '13812345678'); await p.click('#codeBtn'); await p.fill('#code', '8888'); await p.click('#loginBtn')
await p.waitForTimeout(1300)
await p.screenshot({ path: 'shots/live-final-home.png' })
console.log('卡片:', await p.locator('.card').count(), '| 图片加载:', await p.locator('.card img').evaluateAll((xs) => xs.filter((x) => x.naturalWidth > 0).length), '/', await p.locator('.card img').count())
await p.locator('.card .thumb img').nth(1).tap()
await p.waitForTimeout(800)
console.log('详情:', await p.locator('#detail.on').count(), '|', await p.locator('#dtitle').textContent())
await p.screenshot({ path: 'shots/live-final-detail.png' })
await p.click('#backBtn'); await p.waitForTimeout(400)
await p.click('#tabbar button[data-tab="saved"]'); await p.waitForTimeout(500)
console.log('收藏页:', await p.locator('#savedList .item').count(), '项')
await p.screenshot({ path: 'shots/live-final-saved.png' })
await p.click('#tabbar button[data-tab="me"]'); await p.waitForTimeout(400)
await p.screenshot({ path: 'shots/live-final-me.png' })
console.log('失败请求:', bad.length ? bad : '无')
await b.close()
